def normalize_rename_path(value: str) -> str:
    path = value.replace("\\", "/")
    if " => " not in path:
        return path
    if "{" in path and "}" in path:
        prefix, rest = path.split("{", 1)
        middle, suffix = rest.split("}", 1)
        _, new = middle.split(" => ", 1)
        return f"{prefix}{new}{suffix}"
    return path.rsplit(" => ", 1)[-1]


def python_comment_lines(source: str) -> set[int]:
    result: set[int] = set()
    try:
        for token in tokenize.generate_tokens(StringIO(source).readline):
            if token.type == tokenize.COMMENT:
                result.update(range(token.start[0], token.end[0] + 1))
    except (tokenize.TokenError, IndentationError):
        pass
    return result


def exclude_node(
    node: ast.AST,
    effective: set[int],
    exclusions: Counter[str],
    reason: str,
) -> None:
    exclude_range(
        int(getattr(node, "lineno", 0)),
        int(getattr(node, "end_lineno", getattr(node, "lineno", 0))),
        effective,
        exclusions,
        reason,
    )


def exclude_range(
    start: int,
    end: int,
    effective: set[int],
    exclusions: Counter[str],
    reason: str,
) -> None:
    for number in range(max(1, start), max(start, end) + 1):
        if number in effective:
            effective.remove(number)
            exclusions[reason] += 1


def is_protocol_class(node: ast.ClassDef) -> bool:
    return any(
        isinstance(base, ast.Name) and base.id in {"Protocol", "TypedDict"}
        or isinstance(base, ast.Attribute) and base.attr in {"Protocol", "TypedDict"}
        for base in node.bases
    )


def is_schema_class(node: ast.ClassDef) -> bool:
    decorators = {
        decorator.id
        if isinstance(decorator, ast.Name)
        else decorator.func.id
        if isinstance(decorator, ast.Call)
        and isinstance(decorator.func, ast.Name)
        else ""
        for decorator in node.decorator_list
    }
    bases = {
        base.id
        if isinstance(base, ast.Name)
        else base.attr
        if isinstance(base, ast.Attribute)
        else ""
        for base in node.bases
    }
    return bool(
        decorators & {"dataclass", "define", "frozen"}
        or bases & {"BaseModel", "TypedDict"}
    )


def inside_protocol(
    node: ast.AST,
    parents: Mapping[ast.AST, ast.AST],
) -> bool:
    parent = parents.get(node)
    return isinstance(parent, ast.ClassDef) and is_protocol_class(parent)


def overload_only(node: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    decorators = {
        value
        for decorator in node.decorator_list
        for value in (
            decorator.id
            if isinstance(decorator, ast.Name)
            else decorator.attr
            if isinstance(decorator, ast.Attribute)
            else "",
        )
    }
    body_only = all(
        isinstance(item, (ast.Pass, ast.Expr))
        and (
            not isinstance(item, ast.Expr)
            or isinstance(item.value, ast.Constant)
        )
        for item in node.body
    )
    return bool(decorators & {"overload", "abstractmethod"}) and body_only


def exclude_signature_continuation(
    node: ast.FunctionDef | ast.AsyncFunctionDef,
    effective: set[int],
    exclusions: Counter[str],
) -> None:
    if not node.body:
        return
    first_body = node.body[0].lineno
    if first_body <= node.lineno + 1:
        return
    exclude_range(
        node.lineno + 1,
        first_body - 1,
        effective,
        exclusions,
        "signature_continuation",
    )


def literal_node_size(node: ast.AST) -> int:
    return sum(
        isinstance(item, (ast.Constant, ast.Dict, ast.List, ast.Tuple, ast.Set))
        for item in ast.walk(node)
    )


def is_data_literal(node: ast.AST) -> bool:
    executable = any(
        isinstance(
            item,
            (
                ast.Call,
                ast.Await,
                ast.Yield,
                ast.YieldFrom,
                ast.Lambda,
                ast.ListComp,
                ast.SetComp,
                ast.DictComp,
                ast.GeneratorExp,
            ),
        )
        for item in ast.walk(node)
    )
    return not executable


DATA_LITERAL_NAME_PATTERN = re.compile(
    r"(?i)(?:catalog|dataset|records?|fixtures?|samples?|inventory|manifest|"
    r"source_?map|evidence|rows?|lookup_?data|static_?data)"
)


def data_literal_candidate(
    node: ast.AST,
    parents: Mapping[ast.AST, ast.AST],
    literal_size: int,
) -> bool:
    """Separate inflated payload tables from executable algorithm constants.

    A vocabulary set such as WRITE_METHODS or an in-function tuple of package
    roots participates directly in control flow and must not make the audit
    fail merely because it has many short constants.  Data-shaped assignments
    (catalogs, records, manifests, fixtures, evidence rows) remain excluded and
    blocking.  Extremely large unlabelled literals are conservatively treated
    as data as well.
    """

    current = node
    while isinstance(parents.get(current), (ast.Dict, ast.List, ast.Tuple, ast.Set)):
        current = parents[current]
    parent = parents.get(current)
    targets: list[ast.AST] = []
    if isinstance(parent, ast.Assign):
        targets.extend(parent.targets)
    elif isinstance(parent, ast.AnnAssign):
        targets.append(parent.target)
    elif isinstance(parent, ast.NamedExpr):
        targets.append(parent.target)
    names = {
        item.id
        for target in targets
        for item in ast.walk(target)
        if isinstance(item, ast.Name)
    }
    return (
        any(DATA_LITERAL_NAME_PATTERN.search(name) for name in names)
        or literal_size >= 256
    )


def node_line_set(node: ast.AST) -> set[int]:
    start = int(getattr(node, "lineno", 0))
    end = int(getattr(node, "end_lineno", start))
    return set(range(max(1, start), max(start, end) + 1))


def python_adapter_only(tree: ast.Module) -> bool:
    functions = [
        item
        for item in ast.walk(tree)
        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef))
        and not item.name.startswith("_")
    ]
    if not functions:
        return False
    delegated = 0
    substantive = 0
    for function in functions:
        statements = [
            item
            for item in function.body
            if not (
                isinstance(item, ast.Expr)
                and isinstance(item.value, ast.Constant)
                and isinstance(item.value.value, str)
            )
        ]
        calls = sum(isinstance(item, ast.Call) for item in ast.walk(function))
        decisions = sum(
            isinstance(
                item,
                (
                    ast.If,
                    ast.For,
                    ast.AsyncFor,
                    ast.While,
                    ast.Try,
                    ast.Match,
                    ast.With,
                    ast.AsyncWith,
                ),
            )
            for item in ast.walk(function)
        )
        if len(statements) <= 3 and calls <= 2 and decisions == 0:
            delegated += 1
        else:
            substantive += 1
    return delegated >= 3 and substantive == 0


def script_adapter_only(source: str) -> bool:
    functions = len(
        re.findall(
            r"\b(?:function\s+[A-Za-z_$][\w$]*|"
            r"[A-Za-z_$][\w$]*\s*=\s*(?:async\s*)?\([^)]*\)\s*=>)",
            source,
        )
    )
    if functions < 3:
        return False
    decisions = len(re.findall(r"\b(?:if|for|while|switch|try|catch)\b", source))
    direct_returns = len(
        re.findall(
            r"=>\s*[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*\(",
            source,
        )
    ) + len(
        re.findall(
            r"return\s+[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*\(",
            source,
        )
    )
    return decisions == 0 and direct_returns >= functions


def has_generated_marker(source: str) -> bool:
    head = "\n".join(source.splitlines()[:12]).casefold()
    return any(marker in head for marker in GENERATED_MARKERS)


def brace_delta(line: str) -> int:
    return line.count("{") + line.count("[") - line.count("}") - line.count("]")


def likely_data_block(lines: Sequence[str], start: int) -> bool:
    sample = "\n".join(lines[start : min(len(lines), start + 80)])
    property_lines = len(
        re.findall(
            r"(?m)^\s*(?:[A-Za-z_$][\w$]*|['\"][^'\"]+['\"])\s*:",
            sample,
        )
    )
    executable_calls = len(
        re.findall(r"\b[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*\s*\(", sample)
    )
    return property_lines >= 12 and executable_calls <= 2
