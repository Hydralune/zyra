@dataclass(frozen=True, slots=True)
class DiffFile:
    path: str
    added: int
    deleted: int
    added_lines: frozenset[int]

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "added": self.added,
            "deleted": self.deleted,
            "added_lines": sorted(self.added_lines),
        }


@dataclass(frozen=True, slots=True)
class LineClassification:
    effective_lines: frozenset[int]
    exclusions: Mapping[str, int]
    data_as_code_lines: frozenset[int] = frozenset()
    adapter_only: bool = False
    generated: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "effective_lines": sorted(self.effective_lines),
            "exclusions": dict(sorted(self.exclusions.items())),
            "data_as_code_lines": sorted(self.data_as_code_lines),
            "adapter_only": self.adapter_only,
            "generated": self.generated,
        }


