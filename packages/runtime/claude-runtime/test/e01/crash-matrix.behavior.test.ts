import test from "node:test";
import assert from "node:assert/strict";
import { cmd, digest, identity, InvariantError, Journal } from "../../src/e01/kernel.ts";
test("crash-1 prepare_lost_ack recovers deterministically", () => {
  const journal = new Journal();
  const id = identity("crash-run-1", "crash-session-1", "crash-transition-1", 0);
  const transition = cmd("protocol.recovery", "prepare_lost_ack", id, { crash_case: 1, crash_phase: "prepare_lost_ack" }, true);
  const prepared = journal.prepare(transition);
  assert.equal(prepared.status, "pending");
  assert.equal(journal.snapshot().pending.length, 1);
  const effect = journal.effect(transition, { physical_result: "result-1", digest: digest(1) });
  assert.equal(effect.terminal, true);
  assert.equal(effect.ok, true);
  const committed = journal.commit(transition, { recovered: { case_id: 1, phase: "prepare_lost_ack" } }, [{ phase: "prepare_lost_ack", case_id: 1 }]);
  assert.equal(committed.status, "committed");
  assert.equal(committed.after, 1);
  const acked = journal.ack(id.transitionId);
  assert.equal(acked.status, "acked");
  assert.equal(journal.revision, 1);
  assert.equal(journal.snapshot().pending.length, 0);
  assert.equal(journal.snapshot().committed.length, 1);
  assert.equal(journal.snapshot().effects.length, 1);
  assert.equal(journal.snapshot().outbox.length, 1);
  const replay = journal.prepare(transition);
  assert.equal(replay.duplicate, true);
  assert.equal(replay.after, 1);
  const snapshot = journal.snapshot();
  assert.equal(snapshot.owner, "typescript");
  assert.ok(snapshot.digest.startsWith("sha256:"));
});

