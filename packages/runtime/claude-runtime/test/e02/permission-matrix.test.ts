for (const value of cases) {
  test(`permission matrix ${value.id} parses, resolves, classifies, transitions, and restores`, () => {
    const parser = new PermissionRuleParser();
    const rule = parser.parse({
      ruleId: `rule-${value.id}`,
      effect: value.effect,
      source: value.source,
      kind: "tool",
      toolPattern: value.toolName,
      namespacePattern: value.namespace,
      operationPattern: value.operation,
      priority: 100 + value.id.length,
      reason: `matrix rule ${value.id}`,
      revision: 0,
      metadata: { matrix_id: value.id },
    }, {
      now: "2026-07-17T00:00:00.000Z",
    });
    const serialized = parser.serialize(rule);
    const roundTrip = parser.roundTrip(serialized, {
      now: rule.createdAt,
      revision: rule.revision,
      metadata: rule.metadata,
    });
    assert.equal(roundTrip.effect, value.effect);
    assert.equal(roundTrip.scope.toolPattern, value.toolName);
    assert.equal(roundTrip.scope.namespacePattern, value.namespace);
    assert.equal(roundTrip.scope.operationPattern, value.operation);

    const identity = PermissionIdentity.create({
      runId: `run-${value.id}`,
      taskId: `task-${value.id}`,
      sessionId: `session-${value.id}`,
      sessionRevision: 3,
      workerRequestId: `worker-${value.id}`,
      toolCallId: `call-${value.id}`,
      toolName: value.toolName,
      namespace: value.namespace,
      operation: value.operation,
      workspaceRoot: "G:/workspace",
      arguments: {
        path: value.path,
        ...(value.command ? { command: value.command } : {}),
      },
      metadata: {
        matrix_id: value.id,
        annotations: {
          readOnlyHint: value.operation === "read",
          destructiveHint: value.command?.includes("rm -rf") === true,
        },
      },
    });
    const index = new PermissionRuleIndex();
    assert.equal(index.replace([rule], 0), 1);
    assert.equal(index.replace([rule], 1), 1);
    const resolution = index.resolve(identity, "2026-07-17T00:01:00.000Z");
    assert.equal(resolution.winner?.ruleId, rule.ruleId);
    assert.equal(resolution.winner?.effect, value.effect);
    assert.equal(resolution.policyRevision, 1);
    assert.equal(resolution.matches[0]?.matched, true);

    const restored = new PermissionRuleIndex();
    restored.restore(index.snapshot());
    const restoredResolution = restored.resolve(identity, "2026-07-17T00:01:00.000Z");
    assert.equal(restoredResolution.winner?.ruleId, rule.ruleId);
    assert.equal(restored.policyDigest, index.policyDigest);

    const risk = new PermissionRiskRuntime().classify(identity);
    const minimumScore = value.expectedSignal === "tool:shell" ? 0 : value.minimumScore;
    assert.ok(risk.score >= minimumScore);
    assert.ok(risk.score <= 100);
    assert.ok(risk.deterministicSignals.some((signal) => signal.startsWith(value.expectedSignal)));
    assert.equal(risk.assessedArgumentsHash, identity.argumentsDigest);
    assert.equal(risk.classifierCanOverride, false);

    const mode = new PermissionModeRuntime({
      mode: "default",
      interactive: true,
      headless: false,
      changedAt: "2026-07-17T00:00:00.000Z",
    });
    const autonomous = value.mode === "auto" || value.mode === "sealed";
    const transition = mode.transition(value.mode, {
      expectedRevision: 0,
      changedBy: `matrix-${value.id}`,
      reason: `exercise ${value.mode}`,
      interactive: autonomous ? false : true,
      headless: autonomous,
      bypassAvailable: value.mode === "bypassPermissions",
      at: "2026-07-17T00:02:00.000Z",
    });
    assert.equal(transition.to, value.mode);
    assert.equal(mode.mode, value.mode);
    assert.equal(mode.revision, value.mode === "default" ? 0 : 1);
    assert.equal(mode.convertsAskToDeny(), autonomous || value.mode === "dontAsk");
    assert.equal(mode.permitsBypass(), value.mode === "bypassPermissions");

    const restoredMode = new PermissionModeRuntime();
    restoredMode.restore(mode.snapshot());
    assert.deepEqual(restoredMode.state, mode.state);
  });
}
