def profile_for_plan(plan: ExtractionPlan) -> ExtractionRuleProfile:
    profiles = default_extraction_profiles()
    return profiles.get(
        plan.source_repo,
        ExtractionRuleProfile(
            source_repo=plan.source_repo,
            kind=SourceProfileKind.WORKFLOW_RUNTIME,
            includes=tuple(
                IncludeRule(path, plan.owner_unit, tuple(plan.downstream_units), "explicit include", "explicit plan include")
                for path in plan.include_paths
            ),
            min_pilot_files=1,
            max_pilot_files=250,
        ),
    )


def audit_extraction_plan(plan: ExtractionPlan) -> ExtractionRuleAudit:
    return ExtractionRuleEngine(profile_for_plan(plan)).audit_plan(plan)


def build_rule_report_for_plan(plan: ExtractionPlan) -> dict[str, Any]:
    return audit_extraction_plan(plan).to_dict()


def write_rule_report_for_plan(plan: ExtractionPlan, output_path: str | Path) -> Path:
    report = build_rule_report_for_plan(plan)
    path = Path(output_path)
    if not path.is_absolute():
        path = plan.project_root / path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def _iter_plan_candidate_paths(plan: ExtractionPlan) -> list[str]:
    source_root = plan.source_root.resolve()
    candidates: set[str] = set()
    for include in plan.include_paths:
        normalized = normalize_repo_path(include)
        source_path = source_root / normalized
        if source_path.is_file():
            candidates.add(normalized)
        elif source_path.is_dir():
            for child in source_path.rglob("*"):
                if child.is_file():
                    candidates.add(child.relative_to(source_root).as_posix())
        else:
            candidates.add(normalized)
    return sorted(candidates)


def _line_count(path: Path) -> int:
    if not path.exists() or not path.is_file():
        return 0
    try:
        return len(path.read_text(encoding="utf-8", errors="replace").splitlines())
    except OSError:
        return 0


def _matched_content_marker(path: Path, markers: Iterable[str]) -> str:
    if not path.exists() or not path.is_file():
        return ""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    for marker in markers:
        if marker and marker in text:
            return marker
    return ""


def _has_parent_reference(path: str) -> bool:
    return ".." in PurePosixPath(path).parts


def _is_absolute_like(path: str) -> bool:
    parts = PurePosixPath(path).parts
    return path.startswith("/") or bool(parts and ":" in parts[0])
