def _url_arguments(*, required: bool = True) -> tuple:
    return (
        string_rule(
            "url",
            required=required,
            min_length=1,
            max_length=16_384,
            description="Absolute http(s) or policy-owned file URL.",
        ),
        boolean_rule("new_tab", default=False, description="Open in a new target after policy validation."),
        number_rule("timeout_seconds", minimum=0.1, maximum=120.0, default=30.0),
        number_rule("settle_seconds", minimum=0.0, maximum=10.0, default=0.0),
    )


