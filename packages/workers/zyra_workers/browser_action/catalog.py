def _validate_catalog(definitions: Iterable[ActionDefinition]) -> None:
    names: set[str] = set()
    aliases: set[str] = set()
    for definition in definitions:
        if definition.name in names or definition.name in aliases:
            raise ValueError(f"duplicate browser action catalog identity: {definition.name}")
        names.add(definition.name)
        for alias in definition.aliases:
            if alias in names or alias in aliases:
                raise ValueError(f"duplicate browser action catalog alias: {alias}")
            aliases.add(alias)
